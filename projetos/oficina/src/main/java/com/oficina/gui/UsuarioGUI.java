    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        String nome = txtNome.getText();
        String login = txtLogin.getText();
        String senha = new String(pwdSenha.getPassword());
        String confirmacao = new String(pwdConfirmacao.getPassword());
        Perfil perfil = (Perfil) cboPerfil.getSelectedItem();
        boolean ativo = chkAtivo.isSelected();

        Usuario usuario = new Usuario(idSelecionado, nome, login, perfil, ativo);

        try {
            usuarioService.salvar(usuario, senha, confirmacao);
            JOptionPane.showMessageDialog(this, "Usuário salvo com sucesso!", "Sucesso", JOptionPane.INFORMATION_MESSAGE);
            limparFormulario();
            carregarTabela();
        } catch (RegraNegocioException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Validação", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_btnSalvarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        if (idSelecionado == null) {
            JOptionPane.showMessageDialog(this, "Selecione um usuário na tabela para excluir.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int confirmacao = JOptionPane.showConfirmDialog(this,
                "Tem certeza que deseja excluir o usuário selecionado?",
                "Confirmação",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.QUESTION_MESSAGE);

        if (confirmacao == JOptionPane.YES_OPTION) {
            try {
                usuarioService.excluir(idSelecionado);
                JOptionPane.showMessageDialog(this, "Usuário excluído com sucesso!", "Sucesso", JOptionPane.INFORMATION_MESSAGE);
                limparFormulario();
                carregarTabela();
            } catch (RegraNegocioException ex) {
                JOptionPane.showMessageDialog(this, ex.getMessage(), "Validação", JOptionPane.WARNING_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

    private void tblUsuariosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblUsuariosMouseClicked
        int linha = tblUsuarios.getSelectedRow();
        if (linha != -1) {
            idSelecionado = (Integer) tblUsuarios.getValueAt(linha, 0);
            txtNome.setText((String) tblUsuarios.getValueAt(linha, 1));
            txtLogin.setText((String) tblUsuarios.getValueAt(linha, 2));

            String perfilStr = (String) tblUsuarios.getValueAt(linha, 3);
            if ("ADMIN".equalsIgnoreCase(perfilStr)) {
                cboPerfil.setSelectedItem(Perfil.ADMIN);
            } else {
                cboPerfil.setSelectedItem(Perfil.ATENDENTE);
            }

            String ativoStr = (String) tblUsuarios.getValueAt(linha, 4);
            chkAtivo.setSelected("Sim".equalsIgnoreCase(ativoStr));

            // Na edição, senhas ficam em branco por segurança (se mantidas em branco, senha não muda)
            pwdSenha.setText("");
            pwdConfirmacao.setText("");
        }
    }//GEN-LAST:event_tblUsuariosMouseClicked

