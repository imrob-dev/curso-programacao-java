    private void efetuarLogin() {
        String login = txtLogin.getText().trim();
        String senha = new String(pwdSenha.getPassword());

        // RN01: Login e senha são obrigatórios na tela de login
        if (login.isEmpty() || senha.isEmpty()) {
            lblMensagem.setText("Informe o usuário e a senha.");
            return;
        }

        // Autentica contra o banco de dados PostgreSQL com hash SHA-256 (RN02 e RN03)
        boolean autenticado = autenticarNoBanco(login, senha);

        if (autenticado) {
            new TelaPrincipalGUI().setVisible(true);
            this.dispose();
        } else {
            // RN04 e RN05: Login inválido e limite de 3 tentativas
            tentativas++;
            pwdSenha.setText("");
            pwdSenha.requestFocus();

            if (tentativas >= 3) {
                JOptionPane.showMessageDialog(this,
                    "Número máximo de tentativas (3) excedido!\nO sistema será encerrado.",
                    "Acesso Bloqueado",
                    JOptionPane.ERROR_MESSAGE);
                System.exit(0);
            } else {
                lblMensagem.setText("Usuário ou senha inválidos. Tentativa " + tentativas + " de 3.");
            }
        }
    }

    private boolean autenticarNoBanco(String login, String senha) {
        try {
            com.oficina.service.AutenticacaoService authService = new com.oficina.service.AutenticacaoService();
            com.oficina.model.Usuario usuario = authService.entrar(login, senha);
            com.oficina.util.Sessao.iniciar(usuario);
            return true;
        } catch (com.oficina.service.RegraNegocioException ex) {
            return false;
        }
    }

