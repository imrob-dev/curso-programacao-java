    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        Cliente cliente = (Cliente) cboCliente.getSelectedItem();
        String placa = txtPlaca.getText();
        String marca = txtMarca.getText();
        String modelo = txtModelo.getText();
        String anoStr = txtAno.getText();

        Integer ano = null;
        if (anoStr != null && !anoStr.trim().isEmpty()) {
            try {
                ano = Integer.parseInt(anoStr.trim());
            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "O ano deve ser um número válido.", "Validação", JOptionPane.WARNING_MESSAGE);
                return;
            }
        }

        Veiculo veiculo = new Veiculo(idSelecionado, placa, marca, modelo, ano, cliente);

        try {
            veiculoService.salvar(veiculo);
            JOptionPane.showMessageDialog(this, "Veículo salvo com sucesso!", "Sucesso", JOptionPane.INFORMATION_MESSAGE);
            limparFormulario();
            carregarTabela();
        } catch (RegraNegocioException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Validação", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_btnSalvarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        if (idSelecionado == null) {
            JOptionPane.showMessageDialog(this, "Selecione um veículo na tabela para excluir.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int confirmacao = JOptionPane.showConfirmDialog(this,
                "Tem certeza que deseja excluir o veículo selecionado?",
                "Confirmação",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.QUESTION_MESSAGE);

        if (confirmacao == JOptionPane.YES_OPTION) {
            try {
                veiculoService.excluir(idSelecionado);
                JOptionPane.showMessageDialog(this, "Veículo excluído com sucesso!", "Sucesso", JOptionPane.INFORMATION_MESSAGE);
                limparFormulario();
                carregarTabela();
            } catch (RegraNegocioException ex) {
                JOptionPane.showMessageDialog(this, ex.getMessage(), "Validação", JOptionPane.WARNING_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

    private void tblVeiculosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblVeiculosMouseClicked
        int linha = tblVeiculos.getSelectedRow();
        if (linha != -1) {
            idSelecionado = (Integer) tblVeiculos.getValueAt(linha, 0);
            txtPlaca.setText((String) tblVeiculos.getValueAt(linha, 1));
            txtMarca.setText((String) tblVeiculos.getValueAt(linha, 2));
            txtModelo.setText((String) tblVeiculos.getValueAt(linha, 3));
            Object anoObj = tblVeiculos.getValueAt(linha, 4);
            txtAno.setText(anoObj != null ? anoObj.toString() : "");

            String nomeDono = (String) tblVeiculos.getValueAt(linha, 5);
            for (int i = 0; i < cboCliente.getItemCount(); i++) {
                Cliente c = (Cliente) cboCliente.getItemAt(i);
                if (c.getNome().equalsIgnoreCase(nomeDono)) {
                    cboCliente.setSelectedIndex(i);
                    break;
                }
            }
        }
    }//GEN-LAST:event_tblVeiculosMouseClicked

