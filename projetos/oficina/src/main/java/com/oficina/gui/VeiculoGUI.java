    private void carregarComboClientes() {
        try {
            List<Cliente> clientes = clienteService.listar();
            DefaultComboBoxModel<Cliente> model = new DefaultComboBoxModel<>();
            for (Cliente c : clientes) {
                model.addElement(c);
            }
            cboCliente.setModel(model);
        } catch (RegraNegocioException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void carregarTabela() {
        DefaultTableModel modelo = (DefaultTableModel) tblVeiculos.getModel();
        modelo.setRowCount(0);

        try {
            List<Veiculo> veiculos = veiculoService.listar();
            for (Veiculo v : veiculos) {
                modelo.addRow(new Object[]{
                    v.getId(),
                    v.getPlaca(),
                    v.getMarca(),
                    v.getModelo(),
                    v.getAno(),
                    (v.getCliente() != null) ? v.getCliente().getNome() : ""
                });
            }
        } catch (RegraNegocioException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void limparFormulario() {
        idSelecionado = null;
        txtPlaca.setText("");
        txtMarca.setText("");
        txtModelo.setText("");
        txtAno.setText("");
        tblVeiculos.clearSelection();
        if (cboCliente.getItemCount() > 0) {
            cboCliente.setSelectedIndex(0);
        }
        txtPlaca.requestFocus();
    }

